std::string DataHelperC::getLicenceName(const std::string& licence, const std::string& tempPath)
{
  std::string ret;

  std::filesystem::path filterPath = std::filesystem::path(tempPath) / uniqueTempName("LICENSE");
  std::ofstream out(filterPath);
  out << licence;
  out.close();

  std::string cloneCmd = "licensee detect " + filterPath.string() + " --json";
  ExecResult result = DataHelperC::execAndCapture(cloneCmd, tempPath);

  nlohmann::json j = nlohmann::json::parse(result.stdoutText);

  if (j.contains("matched") && j["matched"].is_boolean() && j["matched"].get<bool>())
  {
    if (j.contains("license") && j["license"].is_object())
    {
      auto& license = j["license"];
      if (license.contains("name") && !license["name"].is_null() && license["name"].is_string())
        ret = license["name"].get<std::string>();
    }
  }

  if (ret == "")
  {
    if (j.contains("licenses") && j["licenses"].is_array() && !j["licenses"].empty())
    {
      auto& first = j["licenses"][0];
      if (first.contains("meta") && first["meta"].is_object())
      {
        auto& meta = first["meta"];
        if (meta.contains("title") && !meta["title"].is_null())
          ret = meta["title"].get<std::string>();
      }
    }
  }

  std::error_code remove_ec;
  std::filesystem::remove(filterPath.string(), remove_ec);

  return ret;
}

ExecResult DataHelperC::execAndCapture(const std::string& cmdBase, const std::string& tempPath)
{
  ExecResult res;

  // ensure tempPath exists
  std::error_code ec;
  std::filesystem::create_directories(tempPath, ec);

  // make a unique prefix under tempPath
  std::string prefix = uniqueTempName("exec");
  std::filesystem::path outFile = std::filesystem::path(tempPath) / (prefix + "_out.txt");
  std::filesystem::path errFile = std::filesystem::path(tempPath) / (prefix + "_err.txt");

  // Build full command with stdout + stderr redirection to our files
  // We don't add shell-specific constructs beyond redirection because std::system uses the shell.
  std::string fullCmd = cmdBase + " > \"" + outFile.string() + "\" 2> \"" + errFile.string() + "\"";

  // Execute
  int rc = std::system(fullCmd.c_str());
  res.exitCode = rc;

  // Read stdout
  {
    std::ifstream in(outFile, std::ios::binary);
    if (in.good())
    {
      std::ostringstream ss;
      ss << in.rdbuf();
      res.stdoutText = ss.str();
    }
  }

  // Read stderr
  {
    std::ifstream in(errFile, std::ios::binary);
    if (in.good())
    {
      std::ostringstream ss;
      ss << in.rdbuf();
      res.stderrText = ss.str();
    }
  }

  // cleanup files (best-effort)
  std::error_code remove_ec;
  std::filesystem::remove(outFile, remove_ec);
  std::filesystem::remove(errFile, remove_ec);

  return res;
}

static std::atomic<uint64_t> g_exec_counter{0};

std::string DataHelperC::nowString()
{
  using namespace std::chrono;
  auto t = system_clock::now();
  auto tt = system_clock::to_time_t(t);
  std::tm tm;
#if defined(_WIN32)
  localtime_s(&tm, &tt);
#else
  localtime_r(&tt, &tm);
#endif
  std::ostringstream oss;
  oss << std::put_time(&tm, "%Y%m%d%H%M%S");
  return oss.str();
}

